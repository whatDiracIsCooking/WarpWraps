#!/usr/bin/env python3
"""Generate the `wwr` C ABI from the spec.

One spec in → three artefacts out, so nothing is hand-maintained and nothing can
drift:

  wwr_capi.h    vendor-free C header for bindgen / a C consumer. Opaque PODs,
                plain-C prototypes, no CUDA/HIP name anywhere.
  wwr_capi.cpp  the extern "C" thunks. `import wwr.complex;` and
                `import wwr.runtime_api;`, converts the POD to/from the neutral
                wwr::wwrFloatComplex / wwr::wwrDoubleComplex at the boundary, maps
                the neutral wwr::wwrError_t onto the stable wwr_status enum, and
                forwards into the wwr function. Backend-neutral: it names no vendor
                header and no CUDA-vs-HIP split -- the divergence (architecture.md
                §3, §6) is resolved inside the wwr call / the _map helper, and the
                backend is chosen only by which wwr library is linked.
  ffi.rs        the Rust side: one `extern "C"` block, #[repr(C)] PODs, and ZERO
                #[cfg] -- the whole point. Rust carries no vendor knowledge.

Run: python3 src/capi/generate.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "spec"))
import complex as spec  # noqa: E402

C_FLOAT = {"float": "float", "double": "double"}
RUST_FIELD = {"float": "f32", "double": "f64"}

# Non-POD capi types the ABI uses: C scalars/pointers and the status enum, each
# with its Rust spelling. `wwr_status` is the generated #[repr(i32)] enum.
RUST_SCALAR = {
    "float": "f32",
    "double": "f64",
    "int": "i32",
    "int*": "*mut i32",
    "wwr_status": "wwr_status",
}


def is_pod(name: str) -> bool:
    return any(t["capi"] == name for t in spec.TYPES)


def pod(name: str) -> dict:
    return next(t for t in spec.TYPES if t["capi"] == name)


# ---------------------------------------------------------------------------
# wwr_capi.h — the vendor-free C header
# ---------------------------------------------------------------------------
def status_enumerators() -> list[tuple[str, int]]:
    """The full (enumerator, value) list with fixed ascending values: SUCCESS==0,
    the curated error set from the spec, then UNKNOWN last. One source for the C
    enum, the Rust enum and the _map default -- they cannot drift."""
    errors = [c for c, _ in spec.STATUS]
    names = ["WWR_STATUS_SUCCESS", *errors, "WWR_STATUS_UNKNOWN"]
    return [(n, i) for i, n in enumerate(names)]


def gen_header() -> str:
    L = ["// GENERATED by src/capi/generate.py — do not edit. "
         "Source: src/capi/spec/complex.py",
         "#ifndef WWR_CAPI_H", "#define WWR_CAPI_H", "",
         '#ifdef __cplusplus', 'extern "C" {', "#endif", ""]
    for t in spec.TYPES:
        L.append(f"typedef struct {t['capi']} {{")
        for cty, fn in t["fields"]:
            L.append(f"  {C_FLOAT[cty]} {fn};")
        L.append(f"}} {t['capi']};")
        L.append("")
    # The stable, backend-independent status enum (architecture.md §6). Fixed
    # integer values -- Rust and C agree on them whichever backend the capi links.
    L.append("typedef enum wwr_status {")
    for name, val in status_enumerators():
        L.append(f"  {name} = {val},")
    L.append("} wwr_status;")
    L.append("")
    for f in spec.FUNCTIONS:
        args = ", ".join(f"{a[0]} {a[1]}" for a in f["args"])
        L.append(f"{f['ret']} {f['capi']}({args});")
    L += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif  // WWR_CAPI_H", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------
# wwr_capi.cpp — the backend-neutral extern "C" thunks, forwarding into wwr
# ---------------------------------------------------------------------------
def gen_cpp() -> str:
    L = ["// GENERATED by src/capi/generate.py — do not edit.",
         '#include "wwr_capi.h"', "",
         "import wwr.complex;", "import wwr.runtime_api;", ""]

    # The backend status -> stable wwr_status map (architecture.md §6). Internal
    # (not extern "C"), driven by spec.STATUS, comparing the NEUTRAL wwr::wwr<Name>
    # constants only -- never a vendor name -- so the same thunk source compiles on
    # either backend. Any unrecognised code falls through to WWR_STATUS_UNKNOWN.
    L += ["namespace {",
          "wwr_status _map(wwr::wwrError_t e) {",
          "  if (e == wwr::wwrSuccess) return WWR_STATUS_SUCCESS;"]
    for enum_name, wwr_const in spec.STATUS:
        L.append(f"  if (e == wwr::{wwr_const}) return {enum_name};")
    L += ["  return WWR_STATUS_UNKNOWN;",
          "}",
          "}  // namespace",
          "",
          'extern "C" {',
          ""]

    for f in spec.FUNCTIONS:
        ret = f["ret"]
        args = ", ".join(f"{a[0]} {a[1]}" for a in f["args"])
        L.append(f"{ret} {f['capi']}({args}) {{")

        # Build neutral-typed locals from each POD arg (the §3 boundary crossing).
        # Scalars and pointers (int, int*) pass straight through, no conversion.
        wlocals = {}
        for a in f["args"]:
            aty, an = a
            if is_pod(aty):
                wty = pod(aty)["wwr"]
                wn = f"_w_{an}"
                L.append(f"  {wty} {wn}{{{an}.re, {an}.im}};")
                wlocals[an] = wn

        call_args = ", ".join(wlocals.get(a[1], a[1]) for a in f["args"])
        if ret == "wwr_status":
            # Call the wwr runtime fn and map its neutral status (architecture.md §6).
            L.append(f"  return _map({f['wwr']}({call_args}));")
        elif is_pod(ret):
            L.append(f"  const auto r = {f['wwr']}({call_args});")
            L.append(f"  return {ret}{{r.x, r.y}};")
        else:
            L.append(f"  return {f['wwr']}({call_args});")

        L += ["}", ""]
    L += ["}  // extern \"C\"", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------
# ffi.rs — the Rust side: one extern "C" block, #[repr(C)] PODs, ZERO cfg
# ---------------------------------------------------------------------------
def gen_rust() -> str:
    L = ["// GENERATED by src/capi/generate.py — do not edit.",
         "// Note: NO #[cfg(cuda/hip)] anywhere. The backend is chosen when",
         "// libwwr.capi is built; this Rust is identical for either.", ""]
    for t in spec.TYPES:
        L.append("#[repr(C)]")
        L.append("#[derive(Copy, Clone, Debug)]")
        L.append(f"pub struct {t['capi']} {{")
        for cty, fn in t["fields"]:
            L.append(f"    pub {fn}: {RUST_FIELD[cty]},")
        L.append("}")
        L.append("")
    # The stable status enum, #[repr(i32)] so Rust's values match the C enum
    # exactly (architecture.md §6). Rust turns this into a Result.
    L.append("#[repr(i32)]")
    L.append("#[derive(Copy, Clone, Debug, PartialEq, Eq)]")
    L.append("pub enum wwr_status {")
    for name, val in status_enumerators():
        L.append(f"    {name} = {val},")
    L.append("}")
    L.append("")
    # The link name is the OUTPUT file name of the shared library, NOT the CMake
    # target name: rustc's -l does a literal libwwr_capi.so lookup, so this must
    # match the `OUTPUT_NAME wwr_capi` set on the wwr.capi target in
    # capi/CMakeLists.txt (which also matches the C ABI's wwr_ symbol prefix).
    # Change one and you must change the other, or the Rust driver fails to link.
    L += ['#[link(name = "wwr_capi")]', 'extern "C" {']
    for f in spec.FUNCTIONS:
        args = ", ".join(f"{a[1]}: {_rust_ty(a[0])}" for a in f["args"])
        ret = "" if f["ret"] == "void" else f" -> {_rust_ty(f['ret'])}"
        L.append(f"    pub fn {f['capi']}({args}){ret};")
    L += ["}", ""]
    return "\n".join(L)


def _rust_ty(name: str) -> str:
    if is_pod(name):
        return name
    return RUST_SCALAR[name]


def main() -> None:
    out = Path(__file__).parent / "gen"
    out.mkdir(exist_ok=True)
    (out / "wwr_capi.h").write_text(gen_header())
    (out / "wwr_capi.cpp").write_text(gen_cpp())
    rust = gen_rust()
    (out / "ffi.rs").write_text(rust)
    # The wwr-sys crate ships the binding self-contained (it is installed and
    # path/git-depended on away from this tree, so a sibling `../gen/ffi.rs`
    # include! would dangle). Keep ffi.rs the SINGLE SOURCE by writing the same
    # bytes into the crate here -- `src/lib.rs` only include!s this file, never
    # hand-edited. Regenerating always rewrites both, so the crate cannot go
    # stale. driver.rs still include!s gen/ffi.rs via WWR_CAPI_FFI (rustc-direct,
    # in-tree); the crate is the installed/cargo consumer. Identical content.
    crate_ffi = Path(__file__).parent / "wwr-sys" / "src" / "ffi.rs"
    if crate_ffi.parent.is_dir():
        crate_ffi.write_text(rust)
        print(f"wrote wwr_capi.h, wwr_capi.cpp, ffi.rs -> {out}; "
              f"ffi.rs -> {crate_ffi.parent}")
    else:
        print(f"wrote wwr_capi.h, wwr_capi.cpp, ffi.rs -> {out}")


if __name__ == "__main__":
    main()
