#!/usr/bin/env python3
"""Generate the `wwr` C ABI from the spec.

One spec in → three artefacts out, so nothing is hand-maintained and nothing can
drift:

  wwr_capi.h    vendor-free C header for bindgen / a C consumer. Opaque PODs,
                plain-C prototypes, no CUDA/HIP name anywhere.
  wwr_capi.cpp  the extern "C" thunks. `import wwr.complex;`, converts the POD
                to/from the neutral wwr::wwrFloatComplex / wwr::wwrDoubleComplex
                at the boundary, and forwards into the wwr function. Backend-
                neutral: it names no vendor header and no CUDA-vs-HIP split -- the
                divergence (architecture.md §3) is resolved inside the wwr call,
                and the backend is chosen only by which wwr library is linked.
  ffi.rs        the Rust side: one `extern "C"` block, #[repr(C)] PODs, and ZERO
                #[cfg] -- the whole point. Rust carries no vendor knowledge.

Run: python3 capi/generate.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "spec"))
import complex as spec  # noqa: E402

C_FLOAT = {"float": "float", "double": "double"}
RUST_SCALAR = {"float": "f32", "double": "f64"}
RUST_FIELD = {"float": "f32", "double": "f64"}


def is_pod(name: str) -> bool:
    return any(t["capi"] == name for t in spec.TYPES)


def pod(name: str) -> dict:
    return next(t for t in spec.TYPES if t["capi"] == name)


# ---------------------------------------------------------------------------
# wwr_capi.h — the vendor-free C header
# ---------------------------------------------------------------------------
def gen_header() -> str:
    L = ["// GENERATED by capi/generate.py — do not edit. Source: capi/spec/complex.py",
         "#ifndef WWR_CAPI_H", "#define WWR_CAPI_H", "",
         '#ifdef __cplusplus', 'extern "C" {', "#endif", ""]
    for t in spec.TYPES:
        L.append(f"typedef struct {t['capi']} {{")
        for cty, fn in t["fields"]:
            L.append(f"  {C_FLOAT[cty]} {fn};")
        L.append(f"}} {t['capi']};")
        L.append("")
    for f in spec.FUNCTIONS:
        args = ", ".join(f"{a[0]} {a[1]}" for a in f["args"])
        L.append(f"{f['ret']} {f['capi']}({args});")
    L += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif  // WWR_CAPI_H", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------
# wwr_capi.cpp — the backend-neutral extern "C" thunks, forwarding into wwr
# ---------------------------------------------------------------------------
def gen_cpp() -> str:
    L = ["// GENERATED by capi/generate.py — do not edit.",
         '#include "wwr_capi.h"', "",
         "import wwr.complex;", "", 'extern "C" {', ""]

    for f in spec.FUNCTIONS:
        ret = f["ret"]
        args = ", ".join(f"{a[0]} {a[1]}" for a in f["args"])
        L.append(f"{ret} {f['capi']}({args}) {{")

        # Build neutral-typed locals from each POD arg (the §3 boundary crossing).
        wlocals = {}
        for a in f["args"]:
            aty, an = a
            if is_pod(aty):
                wty = pod(aty)["wwr"]
                wn = f"_w_{an}"
                L.append(f"  {wty} {wn}{{{an}.re, {an}.im}};")
                wlocals[an] = wn

        call_args = ", ".join(wlocals.get(a[1], a[1]) for a in f["args"])
        if is_pod(ret):
            L.append(f"  const auto r = {f['wwr']}({call_args});")
            L.append(f"  return {ret}{{r.x, r.y}};")
        else:
            L.append(f"  return {f['wwr']}({call_args});")

        L += ["}", ""]
    L += ["}  // extern \"C\"", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------
# ffi.rs — the Rust side: one extern "C" block, #[repr(C)] PODs, ZERO cfg
# ---------------------------------------------------------------------------
def gen_rust() -> str:
    L = ["// GENERATED by capi/generate.py — do not edit.",
         "// Note: NO #[cfg(cuda/hip)] anywhere. The backend is chosen when",
         "// libwwr.capi is built; this Rust is identical for either.", ""]
    for t in spec.TYPES:
        L.append("#[repr(C)]")
        L.append("#[derive(Copy, Clone, Debug)]")
        L.append(f"pub struct {t['capi']} {{")
        for cty, fn in t["fields"]:
            L.append(f"    pub {fn}: {RUST_FIELD[cty]},")
        L.append("}")
        L.append("")
    L += ['#[link(name = "wwr.capi")]', 'extern "C" {']
    for f in spec.FUNCTIONS:
        args = ", ".join(f"{a[1]}: {_rust_ty(a[0])}" for a in f["args"])
        ret = "" if f["ret"] == "void" else f" -> {_rust_ty(f['ret'])}"
        L.append(f"    pub fn {f['capi']}({args}){ret};")
    L += ["}", ""]
    return "\n".join(L)


def _rust_ty(name: str) -> str:
    if is_pod(name):
        return name
    return RUST_SCALAR[name]


def main() -> None:
    out = Path(__file__).parent / "gen"
    out.mkdir(exist_ok=True)
    (out / "wwr_capi.h").write_text(gen_header())
    (out / "wwr_capi.cpp").write_text(gen_cpp())
    (out / "ffi.rs").write_text(gen_rust())
    print(f"wrote wwr_capi.h, wwr_capi.cpp, ffi.rs -> {out}")


if __name__ == "__main__":
    main()
